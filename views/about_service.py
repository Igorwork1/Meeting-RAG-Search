import streamlit as st


# --- Header / hero
st.title("About Service")
st.caption("Для тех, кто заходит впервые: что это, как работает и что можно спрашивать.")

# Немного “не стандартных” штук: popover + toast + tabs + expander + metric + status
left, right = st.columns([1.25, 1])

with left:
    st.markdown(
        """
**Что делает сервис**
- Загружаете аудио (встречи/созвоны/интервью).
- Сервис **транскрибирует** запись и сохраняет результат.
- Дальше работает **чат**: вы задаёте вопросы, а ответы строятся по вашим данным (**RAG**: поиск по контенту + генерация ответа).
- Можно получать **короткое саммари**, а также **цитаты** (фрагменты исходного текста) как доказательство.

**Почему это удобно**
- Не нужно “проматывать” часовые записи.
- Быстро вытаскиваете решения, дедлайны, договорённости, задачи, риски.
- Поиск работает даже если формулировка вопроса отличается от того, что было сказано.
"""
    )

    with st.popover("👀 Посмотреть примеры запросов"):
        st.markdown(
            """
- “Какие решения приняли по проекту X?”
- “Какие задачи на меня и какие сроки?”
- “Что обсуждали про бюджет/риски/зависимости?”
- “Какие следующие шаги и кто ответственный?”
- “Были ли спорные моменты? Дай 2 цитаты.”
"""
        )

with right:
    st.subheader("Как устроен поток данных")
    st.info(
        """
**1) Upload** → загрузка аудио и метаданных  
**2) Transcribe** → текст + сегменты (опционально)  
**3) Index** → эмбеддинги в векторном хранилище (pgvector)  
**4) Chat** → поиск релевантных фрагментов + ответ + цитаты
""",
        icon="🧩",
    )

    c1, c2, c3 = st.columns(3)
    c1.metric("Формат", "Аудио", help="MP3/WAV и др. (зависит от бэка)")
    c2.metric("Длина", "~1 час", help="Типичный кейс")
    c3.metric("Цитаты", "2 шт.", help="Короткие фрагменты ~до 200 символов")

st.divider()

# --- Tabs section
tab1, tab2, tab3 = st.tabs(["🚀 Быстрый старт", "🛡️ Приватность", "❓ FAQ"])

with tab1:
    st.markdown(
        """
1. Перейдите во вкладку **Upload** и загрузите файл.
2. Заполните нужные поля (например, **название встречи**).
3. Нажмите **Load** / **Process** (как у вас будет называться кнопка).
4. Перейдите в **Chat** и задайте вопросы.
"""
    )
    with st.expander("Совет: как задавать вопросы, чтобы ответы были точнее"):
        st.markdown(
            """
- Уточняйте контекст: проект, команда, тема, период.
- Просите формат: “в 5 буллетах”, “таблицей”, “с ответственными и сроками”.
- Если нужен факт — просите **цитаты**.
"""
        )

with tab2:
    st.markdown(
        """
- Данные используются **только** для ответа на ваши вопросы.
- Внутри сервиса хранится транскрипт и индекс (эмбеддинги).
- Можно сделать режим: **не сохранять** аудио после транскрибации (по настройке).
"""
    )
    st.warning("Важно: конкретные гарантии зависят от вашего способа деплоя и настроек хранения.", icon="⚠️")

with tab3:
    st.markdown(
        """
**Q: Тайм-коды будут?**  
A: Можно, но вы говорили что они не обязательны — можно скрыть/отключить.

**Q: Сколько ответов возвращает чат?**  
A: По умолчанию 1 лучший ответ. При “общем” вопросе можно показывать до 3 встреч/вариантов.

**Q: Можно ли без даты/названия?**  
A: Да, сервис ищет по всей базе, а если встреч несколько — выберет наиболее похожие по смыслу.
"""
    )

st.divider()