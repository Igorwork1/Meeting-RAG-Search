import streamlit as st

# --- Header / herost.title("About Service")
st.caption("Для тех, кто заходит впервые: что это, как работает и что можно спрашивать.")

# Немного “не стандартных” штук: popover + toast + tabs + expander + metric + status
left, right = st.columns([1.25, 1])

with left:
    st.markdown(
        """
**Что делает сервис**
- Загружаете аудио (встречи/созвоны/интервью).
- Сервис **транскрибирует** запись и сохраняет результат.
- Дальше работает **чат**: вы задаёте вопросы, а ответы строятся по вашим данным (**RAG**: поиск по контенту + генерация ответа).
- Можно получать **короткое саммари**.

**Почему это удобно**
- Не нужно “проматывать” часовые записи.
- Быстро вытаскиваете решения, дедлайны, договорённости, задачи, риски.
- Поиск работает даже если формулировка вопроса отличается от того, что было сказано.
"""
    )

with right:
    st.subheader("Как устроен поток данных")
    st.info(
        """
**1) Upload** → загрузка аудио и метаданных  
**2) Transcribe** → текст + сегменты (опционально)  
**3) Index** → эмбеддинги в векторном хранилище (pgvector)  
**4) Chat** → поиск релевантных фрагментов + ответ
""",
        icon="🧩",
    )

    c1, c2, c3 = st.columns(3)
    c1.metric("Формат", "Аудио", help="MP3/WAV и др. (зависит от бэка)")
    c2.metric("Длина", "~1 час", help="Типичный кейс")
    c3.metric("Результат", "Текст", help="Транскрипт и дальнейшая работа в чате")

st.divider()

# --- Tabs section
tab1, tab2 = st.tabs(["🚀 Быстрый старт", "🛡️ Приватность"])

with tab1:
    st.markdown(
        """
1. Перейдите во вкладку **Upload** и загрузите файл.
2. Заполните нужные поля (например, **название встречи**).
3. Нажмите **Load** / **Process** (как у вас будет называться кнопка).
4. Перейдите в **Chat** и задайте вопросы.
"""
    )

with tab2:
    st.markdown(
        """
- Данные используются **только** для ответа на ваши вопросы.
- Внутри сервиса хранится транскрипт и индекс (эмбеддинги).
"""
    )
    st.warning("Важно: конкретные гарантии зависят от вашего способа деплоя и настроек хранения.", icon="⚠️")

st.divider()